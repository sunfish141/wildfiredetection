import numpy as np
import pandas as pd
from scipy.spatial import cKDTree
from sklearn.metrics import average_precision_score, roc_auc_score

from .incident_transition import observed_incident_state
from .rollout_sequences import snapshot_frame
from .training_grid import cell_from_id


HORIZONS = (1, 2, 4, 8)


def probability_metrics(targets, probabilities):
    y, p = np.asarray(targets, dtype=float), np.asarray(probabilities, dtype=float)
    if len(y) != len(p) or not np.isin(y, [0, 1]).all() or not np.isfinite(p).all() or ((p < 0) | (p > 1)).any():
        raise ValueError("invalid evaluation targets/probabilities")
    if not len(y):
        return {"row_count": 0, "positive_count": 0, "brier_score": None, "pr_auc": None, "roc_auc": None, "ece": None}
    ece = 0.
    bin_ids = np.minimum(9, np.floor(p * 10).astype(int))
    for bin_id in range(10):
        selected = bin_ids == bin_id
        if selected.any():
            ece += selected.mean() * abs(y[selected].mean() - p[selected].mean())
    both = len(np.unique(y)) == 2
    return {"row_count": len(y), "positive_count": int(y.sum()), "brier_score": float(np.mean((y - p)**2)),
            "pr_auc": float(average_precision_score(y, p)) if both else None,
            "roc_auc": float(roc_auc_score(y, p)) if both else None, "ece": float(ece)}


def front_distance(predicted_cells, observed_cells):
    """Distances between boundaries of cumulative newly-burned cell masks.

    Empty fronts are undefined, never assigned a perfect zero distance.
    Cell-centre boundary distances have 1 km discretization, not subcell accuracy.
    """
    def boundary(ids):
        xy = {(cell_from_id(c).x_index, cell_from_id(c).y_index) for c in ids}
        return np.asarray([(x * 1000., y * 1000.) for x, y in sorted(xy)
                           if any((x + dx, y + dy) not in xy for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)))])
    left, right = boundary(predicted_cells), boundary(observed_cells)
    if not len(left) or not len(right):
        return {"symmetric_front_mean_distance_m": None, "front_hausdorff_distance_m": None,
                "front_distance_status": "undefined-empty-predicted-or-observed-front"}
    a = cKDTree(right).query(left)[0]; b = cKDTree(left).query(right)[0]
    return {"symmetric_front_mean_distance_m": float((a.mean() + b.mean()) / 2),
            "front_hausdorff_distance_m": float(max(a.max(), b.max())), "front_distance_status": "measured"}


def score_spatial_horizon(frame, predictions, *, cumulative_predicted, cumulative_actual,
                          cumulative_domain, initial_active):
    frontier = frame.loc[frame.firms_center_has_detection.eq(0)]
    by_id = {p.cell_id: p for p in predictions}
    domain = set(frontier.cell_id)
    actual = set(frontier.loc[frontier.target_newly_burned_12h.eq(1), "cell_id"])
    selected = {p.cell_id for p in predictions if p.will_ignite}
    predicted = selected & domain
    cumulative_domain.update(domain)
    cumulative_predicted.update(selected)
    cumulative_actual.update(actual)
    # Unknown outside-domain predictions remain diagnostics. They do not
    # acquire negative labels simply by being generated by the model.
    cumulative_known = (cumulative_predicted - initial_active) & cumulative_domain
    tp = len(predicted & actual); fp = len(predicted - actual); fn = len(actual - predicted)
    tn = len(domain - predicted - actual)
    probability = [by_id[c].ignition_probability if c in by_id else 0. for c in frontier.cell_id]
    return {**probability_metrics(frontier.target_newly_burned_12h, probability),
            "true_positive": tp, "false_positive": fp, "false_negative": fn, "true_negative": tn,
            "spatial_precision": tp / (tp + fp) if tp + fp else 0.,
            "spatial_recall": tp / (tp + fn) if tp + fn else 0.,
            "accuracy": (tp + tn) / len(domain) if domain else None,
            "domain_coverage": len(domain & set(by_id)) / len(domain) if domain else None,
            "covered_cell_count": len(domain & set(by_id)),
            "model_candidate_count": len(predictions), "outside_domain_candidates": len(set(by_id) - domain),
            "outside_domain_ignitions": len(selected - domain),
            "newly_burned_area_error_km2": len(predicted) - len(actual),
            "cumulative_newly_burned_area_error_km2": len(cumulative_known) - len(cumulative_actual),
            "cumulative_outside_domain_burned_cells": len(cumulative_predicted - cumulative_domain - initial_active),
            **front_distance(cumulative_known, cumulative_actual)}


def evaluate_incident_rollouts(model, examples, sequences, *, terrain_provider):
    reports, exclusions = [], []
    for sequence in sequences:
        if sequence.split not in ("held_incident", "held_region", "later_time"):
            continue
        origin = None
        for index in range(len(sequence.snapshots) - max(HORIZONS) + 1):
            frame = snapshot_frame(examples, sequence.snapshots[index])
            if frame.firms_center_has_detection.eq(1).any():
                origin = index
                break
        if origin is None:
            exclusions.append({"sequence_id": sequence.sequence_id, "split": sequence.split,
                               "reason": "no-observed-origin-with-eight-consecutive-target-windows"})
            continue
        selected_snapshots = sequence.snapshots[origin:origin + max(HORIZONS)]
        state = observed_incident_state(model, snapshot_frame(examples, selected_snapshots[0]))
        initial = {c.cell_id for c in state.active_cells}
        cumulative_predicted, cumulative_actual, cumulative_domain = set(), set(), set()
        for step, snapshot in enumerate(selected_snapshots, start=1):
            result = model.step(state, terrain_provider=terrain_provider)
            metrics = score_spatial_horizon(snapshot_frame(examples, snapshot), result.predictions,
                cumulative_predicted=cumulative_predicted, cumulative_actual=cumulative_actual,
                cumulative_domain=cumulative_domain, initial_active=initial)
            if step in HORIZONS:
                reports.append({"sequence_id": sequence.sequence_id, "incident_group_id": sequence.incident_group_id,
                                "split": sequence.split, "origin": selected_snapshots[0].source_snapshot_time.isoformat(),
                                "horizon_hours": step * 12, "initial_active_count": len(initial),
                                "active_cell_count": len(result.state.active_cells), **metrics})
            state = result.state  # never corrected from subsequent FIRMS/FEDS
    return {"evaluation_version": "incident-open-loop-spatial/v1", "reports": reports,
            "summary": summarize_rollouts(reports), "excluded_sequences": exclusions,
            "target_scope": "released no-centre weak-label domain; cumulative area/front metrics measure new growth since origin",
            "empty_front_policy": "undefined distance; report count; never replace with zero",
            "transition_contract": model.transition_contract()}


def summarize_rollouts(reports):
    groups = defaultdict(list)
    for report in reports:
        groups[(report["split"], report["horizon_hours"])].append(report)
    result = []
    for (split, horizon), rows in sorted(groups.items()):
        counts = {k: sum(r[k] for r in rows) for k in ("true_positive", "false_positive", "false_negative",
                  "true_negative", "row_count", "covered_cell_count", "outside_domain_candidates", "outside_domain_ignitions")}
        tp, fp, fn = (counts[k] for k in ("true_positive", "false_positive", "false_negative"))
        distances = [r["symmetric_front_mean_distance_m"] for r in rows if r["symmetric_front_mean_distance_m"] is not None]
        result.append({"split": split, "horizon_hours": horizon, "sequence_count": len(rows),
                       "incident_count": len({r["incident_group_id"] for r in rows}), **counts,
                       "spatial_precision": tp / (tp + fp) if tp + fp else 0.,
                       "spatial_recall": tp / (tp + fn) if tp + fn else 0.,
                       "accuracy": (tp + counts["true_negative"]) / counts["row_count"] if counts["row_count"] else None,
                       "domain_coverage": counts["covered_cell_count"] / counts["row_count"] if counts["row_count"] else None,
                       "brier_score": sum(r["brier_score"] * r["row_count"] for r in rows if r["brier_score"] is not None) / counts["row_count"] if counts["row_count"] else None,
                       "newly_burned_area_mae_km2": float(np.mean([abs(r["newly_burned_area_error_km2"]) for r in rows])),
                       "cumulative_newly_burned_area_mae_km2": float(np.mean([abs(r["cumulative_newly_burned_area_error_km2"]) for r in rows])),
                       "mean_front_distance_m": float(np.mean(distances)) if distances else None,
                       "defined_front_distance_count": len(distances),
                       "undefined_front_distance_count": len(rows) - len(distances)})
    return result
